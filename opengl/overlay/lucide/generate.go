//go:build ignore

// generate writes codepoints.go, the table from Lucide icon names to the characters of
// lucide.ttf, from the codepoints.json of the lucide-static npm package:
//
//	npm pack lucide-static@<version>   # then unpack it and copy package/font/lucide.ttf here
//	go run generate.go <version> path/to/package/font/codepoints.json
package main

import (
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strings"
)

func main() {
	if len(os.Args) != 3 {
		fmt.Fprintln(os.Stderr, "usage: go run generate.go <lucide version> codepoints.json")
		os.Exit(2)
	}
	if err := generate(os.Args[1], os.Args[2]); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate(version, path string) error {
	data, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	codepoints := map[string]int{}
	if err := json.Unmarshal(data, &codepoints); err != nil {
		return err
	}
	names := make([]string, 0, len(codepoints))
	for name := range codepoints {
		names = append(names, name)
	}
	sort.Strings(names)
	var source strings.Builder
	source.WriteString("// Code generated by generate.go from lucide-static " + version + "; DO NOT EDIT.\n\n")
	source.WriteString("package lucide\n\n")
	source.WriteString("// Version is the lucide-static release the font and this table come from.\n")
	source.WriteString("const Version = \"" + version + "\"\n\n")
	source.WriteString("// codepoints maps every icon name to its character in lucide.ttf.\n")
	source.WriteString("var codepoints = map[string]rune{\n")
	for _, name := range names {
		fmt.Fprintf(&source, "\t%q: 0x%x,\n", name, codepoints[name])
	}
	source.WriteString("}\n")
	formatted, err := format.Source([]byte(source.String()))
	if err != nil {
		return err
	}
	return os.WriteFile("codepoints.go", formatted, 0o644)
}
